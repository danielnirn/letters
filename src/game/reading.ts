/**
 * Picks stories at random and asks their questions in order, so a story stays on screen
 * for a few questions in a row ("read once, answer several").
 */
export function generateReadingList(level: Difficulty, count: number): Word[] {
  const out: Word[] = [];
  let pool: Story[] = [];
  while (out.length < count) {
    if (!pool.length) pool = shuffle(READING_STORIES[level]);
    const story = pool.pop()!;
    for (const [question, answer, ...wrong] of story.qs) {
      if (out.length >= count) break;
      out.push({ word: answer, emoji: story.emoji, hint: question, choices: wrong, story: story.text });
    }
  }
  return out;
}
